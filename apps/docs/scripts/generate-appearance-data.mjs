// Emits .storybook/appearance-data.json: the brand list plus, for every
// brand x mode, the handful of colours Storybook's own chrome needs.
//
// Storybook's manager (the sidebar/toolbar shell) runs in an isolated bundle
// with no access to the app's stylesheets, so it cannot read --color-* at
// runtime - it needs literal values at build time. Those values used to be
// hand-copied into manager.ts, where they encoded not just 18 hex strings but
// also which tonal step each mode's primary maps to; either a seed change or
// a role-tone change would desync the chrome from the components it frames,
// silently. Deriving them from the tokens' own built output removes that
// whole class of drift.
// Run: node scripts/generate-appearance-data.mjs (after `nx run tokens:build`)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRANDS } from '../../../packages/tokens/scripts/generate-palettes.mjs';

const BRAND_NAMES = Object.keys(BRANDS);

const __dirname = dirname(fileURLToPath(import.meta.url));
const tokensJsonDir = resolve(
  __dirname,
  '../../../packages/tokens/dist/json/brands',
);
const outFile = resolve(__dirname, '../.storybook/appearance-data.json');

const MODES = ['light', 'dark', 'high-contrast'];

const readTheme = (brand, mode) =>
  JSON.parse(
    readFileSync(resolve(tokensJsonDir, brand, `theme-${mode}.json`), 'utf-8'),
  ).color;

const appearance = {
  $description:
    'Generated by apps/docs/scripts/generate-appearance-data.mjs from packages/tokens - do not edit directly.',
  brands: BRAND_NAMES,
  modes: MODES,
  themes: Object.fromEntries(
    BRAND_NAMES.map((brand) => [
      brand,
      Object.fromEntries(
        MODES.map((mode) => {
          const c = readTheme(brand, mode);
          return [
            mode,
            {
              // Accent + its contrasting foreground, for the logo mark and
              // selected-item states.
              primary: c.primary,
              onPrimary: c['on-primary'],
              // Chrome neutrals, taken from the same surface ramp the
              // components use, so the shell and the canvas agree.
              appBg: c['surface-container-low'],
              appContentBg: c.surface,
              appBorderColor: c['outline-variant'],
              textColor: c['on-surface'],
              textMutedColor: c['on-surface-variant'],
              inverseText: c['inverse-on-surface'],
            },
          ];
        }),
      ),
    ]),
  ),
};

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${JSON.stringify(appearance, null, 2)}\n`);
console.log(
  `Wrote ${outFile} (${BRAND_NAMES.length} brands x ${MODES.length} modes)`,
);

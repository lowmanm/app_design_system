// Storybook-only: rewrites each brand's built token CSS (normally consumed
// one-brand-per-app, via :root/[data-theme]) to also require
// [data-brand="<brand>"], then concatenates all brands into one file. This
// lets the docs site load every brand at once and flip between them with a
// toolbar global (see .storybook/preview.ts) purely for review purposes -
// it is NOT the production consumption contract. A real app still picks
// one brand at install time and loads only that brand's CSS (see
// packages/tokens' README) - loading all three, as this file does, would
// be wasted bytes in production.
// Run: node scripts/generate-brand-css.mjs (after `nx run tokens:build`)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BRANDS as BRAND_SEEDS } from '../../../packages/tokens/scripts/generate-palettes.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const tokensBrandsDir = resolve(
  __dirname,
  '../../../packages/tokens/dist/css/brands',
);
const outFile = resolve(__dirname, '../src/generated/brand-themes.css');

// Derived from the tokens package's BRANDS map - the single place a
// business-unit brand is declared.
const BRANDS = Object.keys(BRAND_SEEDS);
const MODES = [
  {
    file: 'theme-light.css',
    from: ':root, [data-theme="light"] {',
    to: (brand) =>
      `[data-brand="${brand}"]:root, [data-brand="${brand}"][data-theme="light"] {`,
  },
  {
    file: 'theme-dark.css',
    from: '[data-theme="dark"] {',
    to: (brand) => `[data-brand="${brand}"][data-theme="dark"] {`,
  },
  {
    file: 'theme-high-contrast.css',
    from: '[data-theme="high-contrast"] {',
    to: (brand) => `[data-brand="${brand}"][data-theme="high-contrast"] {`,
  },
];

let output = `/**
 * Generated by apps/docs/scripts/generate-brand-css.mjs - do not edit directly.
 * Storybook-only brand switcher: scopes each brand's token CSS under
 * [data-brand="<brand>"] so the docs site can flip brands at runtime via a
 * toolbar global. Not part of the production consumption contract.
 */

`;

for (const brand of BRANDS) {
  for (const mode of MODES) {
    const path = resolve(tokensBrandsDir, brand, mode.file);
    const raw = readFileSync(path, 'utf8');
    if (!raw.includes(mode.from)) {
      throw new Error(
        `Expected selector ${JSON.stringify(mode.from)} not found in ${path} - has the tokens CSS output format changed?`,
      );
    }
    output += raw.replace(mode.from, mode.to(brand)) + '\n';
  }
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, output);
console.log(`Wrote ${outFile}`);
